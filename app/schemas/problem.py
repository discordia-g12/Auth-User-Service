from typing import Any

from pydantic import BaseModel, Field


class ProblemDetails(BaseModel):
    """RFC 7807 compliant problem details schema."""

    type: str = Field(default="about:blank", description="A URI reference that identifies the problem type")
    title: str = Field(..., description="A short, human-readable summary of the problem type")
    status: int = Field(..., description="The HTTP status code generated by the origin server")
    detail: str = Field(..., description="A human-readable explanation specific to this occurrence of the problem")
    instance: str | None = Field(default=None, description="A URI reference that identifies the specific occurrence")
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None, description="List of fields that failed boundary validation"
    )
